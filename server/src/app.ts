import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import authRoutes from './routes/authRoutes.js';
import ticketRoutes from './routes/ticketRoutes.js';
import dashboardRoutes from './routes/dashboardRoutes.js';
import {notFound,errorHandler} from './middleware/error.js';
import './events/listeners.js';
const app=express();
app.use(helmet());
app.use(cors({origin:process.env.CLIENT_URL || 'http://localhost:5173'}));
app.use(express.json({limit:'1mb'}));
app.use(morgan('dev'));
app.use('/api',rateLimit({windowMs:15*60*1000,max:300,standardHeaders:true,legacyHeaders:false}));
app.get('/api/health',(_req,res)=>res.json({success:true,message:'HelpDesk API is healthy'}));
app.use('/api/auth',authRoutes);app.use('/api/tickets',ticketRoutes);app.use('/api/dashboard',dashboardRoutes);
app.use(notFound);app.use(errorHandler);
export default app;
